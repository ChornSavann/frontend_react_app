export const changeAppLanguage = (newLang) => {
    localStorage.setItem("app_lang", newLang);
    document.documentElement.lang = newLang;
    window.dispatchEvent(new CustomEvent("app-lang-change", { detail: { lang: newLang } }));
};

export const useTranslation = () => {
    const [lang, setLang] = useState(() => localStorage.getItem("app_lang") || "en");

    useEffect(() => {
        const handleLangChange = (e) => {
            setLang(e.detail?.lang || localStorage.getItem("app_lang") || "en");
        };
        window.addEventListener("app-lang-change", handleLangChange);
        return () => window.removeEventListener("app-lang-change", handleLangChange);
    }, []);

    const t = translations[lang] || translations.en;
    const toggleLang = () => changeAppLanguage(lang === "en" ? "km" : "en");

    return { lang, t, toggleLang, setLang: changeAppLanguage };
};